-- =====================================================================
-- Base de datos: bd_prestamos  (propiedad exclusiva del MS Préstamos)
-- Motor: PostgreSQL 16 (también compatible con H2 en modo PostgreSQL para pruebas)
-- id_usuario e id_recurso son referencias lógicas a otros servicios: no llevan FK.
-- =====================================================================

CREATE SEQUENCE IF NOT EXISTS prestamo_seq START WITH 100;
CREATE SEQUENCE IF NOT EXISTS multa_seq START WITH 1;

CREATE TABLE IF NOT EXISTS prestamo (
    id_prestamo                 VARCHAR(20)  PRIMARY KEY,          -- P-0100
    id_usuario                  VARCHAR(20)  NOT NULL,             -- ref. lógica a Usuarios
    id_recurso                  VARCHAR(20)  NOT NULL,             -- ref. lógica a Catálogo
    titulo_recurso              VARCHAR(200) NOT NULL,             -- copia para el historial (CU07)
    categoria_recurso           VARCHAR(20)  NOT NULL,             -- copia para calcular el plazo (RN05)
    estado                      VARCHAR(20)  NOT NULL,
    motivo                      VARCHAR(40),
    fecha_solicitud             TIMESTAMP WITH TIME ZONE NOT NULL,
    reserva_vigente_hasta       TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_entrega               TIMESTAMP WITH TIME ZONE,
    fecha_devolucion_estimada   DATE         NOT NULL,
    fecha_devolucion_real       TIMESTAMP WITH TIME ZONE,
    renovaciones                INTEGER      NOT NULL DEFAULT 0,
    recurso_danado              BOOLEAN      NOT NULL DEFAULT FALSE,
    version                     BIGINT       NOT NULL DEFAULT 0,   -- bloqueo optimista
    CONSTRAINT ck_prestamo_estado CHECK (estado IN ('PENDIENTE_ENTREGA','ACTIVO','VENCIDO','FINALIZADO','RECHAZADO')),
    CONSTRAINT ck_prestamo_renov  CHECK (renovaciones >= 0),
    CONSTRAINT ck_prestamo_motivo CHECK (estado <> 'RECHAZADO' OR motivo IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_prestamo_usuario_estado ON prestamo (id_usuario, estado);
CREATE INDEX IF NOT EXISTS ix_prestamo_estado_limite  ON prestamo (estado, fecha_devolucion_estimada);
CREATE INDEX IF NOT EXISTS ix_prestamo_estado_reserva ON prestamo (estado, reserva_vigente_hasta);
CREATE INDEX IF NOT EXISTS ix_prestamo_recurso        ON prestamo (id_recurso, estado);

CREATE TABLE IF NOT EXISTS multa (
    id_multa          VARCHAR(20)   PRIMARY KEY,                  -- M-0001
    id_prestamo       VARCHAR(20)   NOT NULL REFERENCES prestamo (id_prestamo),
    id_usuario        VARCHAR(20)   NOT NULL,                     -- copia para consultar sin JOIN
    dias_retraso      INTEGER       NOT NULL,
    tarifa_diaria     NUMERIC(10,2) NOT NULL,                     -- tarifa vigente al generarla
    monto_calculado   NUMERIC(10,2) NOT NULL,
    estado_pago       VARCHAR(10)   NOT NULL DEFAULT 'PENDIENTE',
    fecha_generacion  TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_resolucion  TIMESTAMP WITH TIME ZONE,
    version           BIGINT        NOT NULL DEFAULT 0,             -- bloqueo optimista (dos cobros a la vez)
    CONSTRAINT ck_multa_estado CHECK (estado_pago IN ('PENDIENTE','PAGADA','CANCELADA')),
    CONSTRAINT ck_multa_valores CHECK (dias_retraso > 0 AND monto_calculado >= 0 AND tarifa_diaria >= 0)
);

CREATE INDEX IF NOT EXISTS ix_multa_usuario_estado ON multa (id_usuario, estado_pago);
CREATE INDEX IF NOT EXISTS ix_multa_prestamo       ON multa (id_prestamo);

-- Bandeja de salida (D6): avisos y cambios de Catálogo pendientes de enviar, con reintentos.
CREATE TABLE IF NOT EXISTS evento_pendiente (
    id_evento           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                VARCHAR(30)   NOT NULL,
    payload             TEXT          NOT NULL,                   -- JSON
    clave_idempotencia  VARCHAR(120)  NOT NULL,
    id_prestamo         VARCHAR(20),                                -- para enviar en orden los cambios de Catálogo
    estado              VARCHAR(10)   NOT NULL DEFAULT 'PENDIENTE',
    intentos            INTEGER       NOT NULL DEFAULT 0,
    proximo_intento     TIMESTAMP WITH TIME ZONE NOT NULL,
    ultimo_error        VARCHAR(300),
    fecha_creacion      TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_envio         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ux_evento_clave UNIQUE (clave_idempotencia),
    CONSTRAINT ck_evento_tipo CHECK (tipo IN ('NOTIFICACION','CATALOGO_LIBERAR','CATALOGO_ENTREGA','CATALOGO_DEVOLUCION')),
    CONSTRAINT ck_evento_estado CHECK (estado IN ('PENDIENTE','ENVIADO','FALLIDO'))
);

CREATE INDEX IF NOT EXISTS ix_evento_pendientes ON evento_pendiente (estado, proximo_intento);

-- Demanda no atendida (RN06): solicitudes rechazadas por falta de existencias.
-- Mientras exista una reciente de otro usuario, el préstamo de ese recurso no se renueva.
CREATE TABLE IF NOT EXISTS solicitud_espera (
    id_solicitud    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recurso      VARCHAR(20) NOT NULL,
    id_usuario      VARCHAR(20) NOT NULL,
    fecha_registro  TIMESTAMP WITH TIME ZONE NOT NULL,
    atendida        BOOLEAN     NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS ix_espera_recurso ON solicitud_espera (id_recurso, atendida, fecha_registro);

-- Candado por usuario (RN03): serializa las solicitudes simultáneas de un mismo usuario para que
-- el límite de préstamos y la regla de "un recurso a la vez" se revisen sin carreras.
CREATE TABLE IF NOT EXISTS cupo_usuario (
    id_usuario  VARCHAR(20) PRIMARY KEY
);

-- Actualización de bases creadas con la versión anterior del esquema
ALTER TABLE multa ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE evento_pendiente ADD COLUMN IF NOT EXISTS id_prestamo VARCHAR(20);
CREATE INDEX IF NOT EXISTS ix_evento_prestamo ON evento_pendiente (id_prestamo, estado);
